require('dotenv').config();
const express=require('express');
const path=require('path');
const helmet=require('helmet');
const cors=require('cors');
const rateLimit=require('express-rate-limit');
const {initDb}=require('./db');
const api=require('./routes');
const {notFound,errorHandler}=require('./middleware/errors');
const app=express();
app.use(helmet({contentSecurityPolicy:false}));
app.use(cors({origin:process.env.CLIENT_ORIGIN||true}));
app.use(express.json({limit:'20kb'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,max:30,standardHeaders:true,legacyHeaders:false}));
app.use('/api',api);
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'PageVault API'}));
app.use(express.static(path.join(__dirname,'..')));
app.use(notFound); app.use(errorHandler);
const PORT=process.env.PORT||3000;
if(require.main===module){initDb().then(()=>app.listen(PORT,()=>console.log(`PageVault running at http://localhost:${PORT}`))).catch(err=>{console.error(err);process.exit(1);});}
module.exports=app;
