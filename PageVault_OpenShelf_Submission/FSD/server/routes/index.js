const express=require('express');
const {register,login}=require('../controllers/authController');
const books=require('../controllers/bookController');
const requests=require('../controllers/requestController');
const auth=require('../middleware/auth');
const {searchBooks}=require('../services/openLibrary');
const router=express.Router();
router.post('/auth/register',register);
router.post('/auth/login',login);
router.get('/auth/me',auth,(req,res)=>res.json({user:req.user}));
router.get('/books',auth,books.list);
router.post('/books',auth,books.create);
router.get('/books/mine',auth,books.mine);
router.get('/open-library',auth,async(req,res,next)=>{try{res.json(await searchBooks(String(req.query.q||'')));}catch(e){next(e);}});
router.get('/requests',auth,requests.list);
router.post('/books/:bookId/requests',auth,requests.create);
router.patch('/requests/:id',auth,requests.update);
module.exports=router;
